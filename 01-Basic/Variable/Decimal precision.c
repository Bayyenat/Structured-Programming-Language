#include<stdio.h>
int main() {

    float pi = 3.14159265;

    printf("full value %f\n", pi);
    printf("2 digits after decimal will be %.2f\n", pi);
    printf("3 digits after decimal will be %.3f\n", pi);
    printf("4 digits after decimal will be %.4f\n", pi);
    printf("5 digits after decimal will be %.5f\n", pi);
    printf("6 digits after decimal will be %.6f\n", pi);
return 0;
}
